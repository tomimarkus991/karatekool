-- The club's calendar. Reference data (Groups, trailers) keeps the ids it had in Supabase so the
-- hosted Events can be copied over as they are.

create table club_group (
    id     bigint generated by default as identity primary key,
    letter text not null unique
);

create table trailer (
    id   bigint generated by default as identity primary key,
    text text not null
);

-- A saved Multi-day event title
create table preset (
    id    bigint generated by default as identity primary key,
    title text not null
);

create table event (
    id          bigint generated by default as identity primary key,
    kind        text        not null check (kind in ('TRAINING', 'ALL_DAY', 'MULTI_DAY')),
    starts_at   timestamptz not null,
    -- Multi-day events only: their last day
    ends_at     timestamptz,
    highlighted boolean     not null default false,
    description text,
    trailer_id  bigint references trailer (id),
    -- All-day events only
    title       text,
    subtitle    text,
    -- Multi-day events only; a Preset still in use can't be deleted
    preset_id   bigint references preset (id),
    created_at  timestamptz not null default now(),
    updated_at  timestamptz not null default now()
);

create index event_starts_at_idx on event (starts_at);

create table event_group (
    event_id bigint not null references event (id) on delete cascade,
    group_id bigint not null references club_group (id),
    primary key (event_id, group_id)
);

